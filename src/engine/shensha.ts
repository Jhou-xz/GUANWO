export interface 柱支干 { 天干: string; 地支: string }
export interface 煞ctx { 日干: string; 年干: string; 年支: string; 日支: string; 月支: string }

// 词馆 = 日干长生位（学堂词馆，取日干五行长生支）
function 长生支(干: string): string {
  const 起 = 长生起[干]
  if (起 === undefined) return ''
  return 地支序[起] // 长生序[0]=长生，对应地支起点
}

// 给一柱算出它身上的神煞
export function 算神煞(柱: 柱支干, ctx: 煞ctx): string[] {
  const r: string[] = []
  const z = 柱.地支; const g = 柱.天干
  const add = (名: string) => { if (!r.includes(名)) r.push(名) }

  // 干系（日干 + 年干 双参照）
  for (const [名, tbl] of Object.entries(按日干年干)) {
    if (tbl[ctx.日干]?.includes(z) || tbl[ctx.年干]?.includes(z)) add(名)
  }
  // 干系（仅日干）
  for (const [名, tbl] of Object.entries(按日干)) {
    if (tbl[ctx.日干]?.includes(z)) add(名)
  }
  // 三合系（年支 + 日支 双参照）
  for (const ref of [ctx.年支, ctx.日支]) {
    const 局 = 三合局[ref]
    if (!局) continue
    for (const [名, tbl] of Object.entries(按三合)) if (tbl[局] === z) add(名)
  }
  // 月支系：天德 / 月德（看天干，也可落地支）
  if (天德[ctx.月支] === g || 天德[ctx.月支] === z) add('天德贵人')
  if (月德[ctx.月支] === g || 月德[ctx.月支] === z) add('月德贵人')
  // 德秀贵人（月局 + 天干）
  const 月局 = 三合局[ctx.月支]
  if (月局 && 德秀[月局] && (德秀[月局].德.includes(g) || 德秀[月局].秀.includes(g))) add('德秀贵人')
  // 血刃（月支）
  if (血刃[ctx.月支] === z) add('血刃')
  // 披麻（年支退三位）
  const yi = 地支序.indexOf(ctx.年支)
  if (yi >= 0 && 地支序[(yi - 3 + 12) % 12] === z) add('披麻')
  // 词馆（日干长生位）
  if (长生支(ctx.日干) === z) add('词馆')

  return r
}
