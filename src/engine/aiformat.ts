// AI 数据层 —— 把命盘「无损」序列化为结构化文本，供 AI 直接提取（而非截图）。
// 原则：UI 与 AI 读同一份引擎数据；这里是命盘 → 文本的唯一规范出口。

import type { 命盘, BaziChart } from './types'

const 柱名: { key: keyof BaziChart['四柱']; label: string }[] = [
  { key: '年', label: '年柱' }, { key: '月', label: '月柱' }, { key: '日', label: '日柱' }, { key: '时', label: '时柱' },
]

// 八字：四柱全字段 + 旺衰 + 司令/胎元/命宫/身宫 + 调候 + 起运 + 大运全列
export function 八字详述(b: BaziChart): string {
  const 柱行 = 柱名.map(({ key, label }) => {
    const p = b.四柱[key]
    const 藏 = p.藏干.map((h) => `${h.干}${h.十神}`).join('') || '—'
    const 十神 = key === '日' ? '日主' : p.干十神
    const 煞 = p.神煞?.length ? p.神煞.join('/') : '无'
    return `${label}：${p.天干}${p.地支}｜十神${十神}｜藏干${藏}｜星运${p.星运 ?? '—'}｜自坐${p.自坐 ?? '—'}｜旬空${p.旬空 ?? '—'}｜纳音${p.纳音}｜神煞${煞}`
  }).join('\n')

  const wx = b.五行统计
  const ws = b.五行旺衰
  const 旺衰 = ws ? `（月令${ws.月令五行}：木${ws.木} 火${ws.火} 土${ws.土} 金${ws.金} 水${ws.水}）` : ''

  const 调候 = b.调候
    ? `调候用神（穷通宝鉴·${b.调候.标题}）：${b.调候.用神.join('')}｜本盘${b.调候.透.length ? '透' + b.调候.透.join('') : ''}${b.调候.藏.length ? ' 藏' + b.调候.藏.join('') : ''}${!b.调候.透.length && !b.调候.藏.length ? '用神不显、调候偏弱' : ''}`
    : ''

  const 大运 = b.大运.map((d) => `${d.干支}(${d.起始虚岁}岁/${d.起始公历年}年,${d.干十神 ?? ''}${d.长生 ? '·' + d.长生 : ''})`).join(' → ')

  return [
    `日主：${b.日主}${b.日主五行}` + (b.司令 ? `｜月令司令：${b.司令}` : '') + (b.命宫 ? `｜命宫：${b.命宫}` : '') + (b.身宫 ? `｜身宫：${b.身宫}` : '') + (b.胎元 ? `｜胎元：${b.胎元}` : ''),
    柱行,
    `五行计数：木${wx.木} 火${wx.火} 土${wx.土} 金${wx.金} 水${wx.水} ${旺衰}`,
    调候,
    `起运：${b.起运.方向}，约${b.起运.虚岁}岁${b.起运.月 ? b.起运.月 + '月' : ''}起${b.起运.交运公历 ? `（交运 ${b.起运.交运公历}）` : ''}`,
    `大运：${大运}`,
  ].filter(Boolean).join('\n')
}

// 紫微：十二宫全星（主星+辅星+杂曜+四化+亮度）+ 命身主 + 大限
export function 紫微详述(z: 命盘['紫微']): string {
  const 星文 = (s: { 名: string; 亮度?: string; 四化?: string }) => s.名 + (s.亮度 ? s.亮度 : '') + (s.四化 ? `化${s.四化}` : '')
  // 生年四化汇总
  const 四化: Record<string, string> = {}
  z.十二宫.forEach((g) => [...g.主星, ...g.辅星].forEach((s) => { if (s.四化) 四化[s.四化] = s.名 }))
  const 四化文 = ['禄', '权', '科', '忌'].filter((h) => 四化[h]).map((h) => `${四化[h]}化${h}`).join('、')
  const 宫 = z.十二宫.filter((g) => g.宫名).map((g) => {
    const 主 = g.主星.map(星文).join('') || '空宫'
    const 辅 = g.辅星.map(星文).join('')
    const 杂 = g.杂曜.map((s) => s.名).join('')
    const 标 = (g.是身宫 ? '〔身宫〕' : '') + (g.是来因宫 ? '〔来因〕' : '')
    const 神 = [g.长生十二神, g.博士十二神, g.将前十二神, g.岁前十二神].filter(Boolean).join('·')
    return `${g.宫名}(${g.天干}${g.地支})${标}：主星${主}${辅 ? '｜辅' + 辅 : ''}${杂 ? '｜杂' + 杂 : ''}${神 ? '｜神煞' + 神 : ''}｜大限${g.大限.起虚岁}-${g.大限.止虚岁}`
  }).join('\n')
  return `五行局：${z.五行局}；命主${z.命主}、身主${z.身主}；命宫在${z.命宫地支}、身宫在${z.身宫地支}${四化文 ? `\n生年四化：${四化文}` : ''}\n${宫}`
}

// 整盘无损叙述（解读 / 追问共用）
export function 命盘详述(c: 命盘): string {
  const m = c.元信息
  const 真 = m.真太阳时?.启用 ? `；真太阳时校正后 ${m.真太阳时.校正后时刻}` : ''
  return [
    `【基本】性别${m.输入.性别}｜公历${m.公历}｜农历${m.农历}｜${m.时辰}${真}`,
    `\n【八字】\n${八字详述(c.八字)}`,
    `\n【紫微斗数】\n${紫微详述(c.紫微)}`,
  ].join('\n')
}
