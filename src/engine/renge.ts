// 观我人格 —— 「东方版 MBTI」：从命盘确定性推导出一个可认领、可分享的人格「型」。
// 四个二元轴 → 4 字代号（如「显主创暖」）+ 16 原型名号（如「燎原者」）+ 五行系。
// 纯函数、零 AI、与排盘同源（复用八字五行统计/月令/日主），同生辰必同型。
//
// 四轴皆从「日主 + 五行统计（天干及全部藏干各计 1，透明计数）+ 月令」推出：
//   朝向 显/隐 ← 日主阴阳（阳=显·外放，阴=隐·内蕴）
//   底盘 主/应 ← 身强身弱（扶=同类比劫+印 vs 耗=食伤+财+官杀，月令加权）
//   心法 创/守 ← 十神族（食伤+财=创·点子 vs 官杀+印=守·靠谱）
//   气候 暖/凉 ← 木火(生发) vs 金水(收藏)；土为枢、不投票
// 这是传统文化视角的「类型」，非吉凶断语；判定透明，仅供自我探索与娱乐。

import type { 命盘 } from './types'

const 阳干 = new Set(['甲', '丙', '戊', '庚', '壬'])
const 干五行: Record<string, string> = {
  甲: '木', 乙: '木', 丙: '火', 丁: '火', 戊: '土', 己: '土', 庚: '金', 辛: '金', 壬: '水', 癸: '水',
}
// 我生者（食伤）/ 我克者（财）
const 我生: Record<string, string> = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' }
const 我克: Record<string, string> = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' }
const 反查 = (m: Record<string, string>, v: string) => Object.keys(m).find((k) => m[k] === v)!

type 五行计 = { 木: number; 火: number; 土: number; 金: number; 水: number }
type 极 = '显' | '隐' | '主' | '应' | '创' | '守' | '暖' | '凉'

// 每个极的短标签（chips 用），与轴义对齐
