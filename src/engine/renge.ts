export function 观我人格(chart: 命盘): 人格 {
  const 日主 = chart.八字.日主
  const me = 干五行[日主] ?? '木'
  const s = chart.八字.五行统计 as unknown as 五行计

  const 印 = 反查(我生, me)   // 生我者
  const 食伤 = 我生[me]        // 我生者
  const 财 = 我克[me]          // 我克者
  const 官杀 = 反查(我克, me)  // 克我者

  // 朝向
  const 朝向: 极 = 阳干.has(日主) ? '显' : '隐'

  // 底盘：扶（同类比劫 + 印）vs 耗（食伤 + 财 + 官杀），月令加权
  let 扶 = s[me as keyof 五行计] + s[印 as keyof 五行计]
  let 耗 = s[食伤 as keyof 五行计] + s[财 as keyof 五行计] + s[官杀 as keyof 五行计]
  const 月令 = chart.八字.五行旺衰?.月令五行
  if (月令) { if (月令 === me || 月令 === 印) 扶 += 2; else 耗 += 1 } // 得令显著加扶，失令略加耗
  const 底盘: 极 = 扶 >= 耗 ? '主' : '应'

  // 心法：创（食伤+财）vs 守（官杀+印）；平局按日主阴阳破（阳偏创、阴偏守）
  const 创力 = s[食伤 as keyof 五行计] + s[财 as keyof 五行计]
  const 守力 = s[官杀 as keyof 五行计] + s[印 as keyof 五行计]
  const 心法: 极 = 创力 > 守力 ? '创' : 创力 < 守力 ? '守' : (阳干.has(日主) ? '创' : '守')

  // 气候：木火 vs 金水（土为枢、不投票），平局归暖
  const 气候: 极 = (s.木 + s.火) >= (s.金 + s.水) ? '暖' : '凉'

  // 五行系：最旺元素
  const keys: (keyof 五行计)[] = ['木', '火', '土', '金', '水']
  let 元素: keyof 五行计 = '木'
  for (const k of keys) if (s[k] > s[元素]) 元素 = k

  const 代号 = `${朝向}${底盘}${心法}${气候}`
  const t = 原型表[代号]
  return {
    代号,
    名号: t.名号,
    一句话: t.一句话,
    元素,
    朝向, 底盘, 心法, 气候,
    标签: [极标签[朝向], 极标签[底盘], 极标签[心法], 极标签[气候]],
    解释: { 朝向: 解释模板[朝向], 底盘: 解释模板[底盘], 心法: 解释模板[心法], 气候: 解释模板[气候] },
  }
}
