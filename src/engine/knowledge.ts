// ── 取数辅助 ──

export interface 五行解读 { 最旺: string; 最弱: string; 缺: string[] }

export function 解读五行(统计: { 木: number; 火: number; 土: number; 金: number; 水: number }): 五行解读 {
  const keys = ['木', '火', '土', '金', '水'] as const
  let 最旺: typeof keys[number] = keys[0], 最弱: typeof keys[number] = keys[0]
  keys.forEach((k) => {
    if (统计[k] > 统计[最旺]) 最旺 = k
    if (统计[k] < 统计[最弱]) 最弱 = k
  })
  const 缺 = keys.filter((k) => 统计[k] === 0)
  return { 最旺, 最弱, 缺 }
}
