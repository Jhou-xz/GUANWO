// 对账测试 —— 引擎的信誉门槛。盘错即红。
// 值已用 lunar-typescript 输出核对；边界命例验证流派规则正确。

import { describe, it, expect } from 'vitest'
import { 排盘, 支关系 } from './index'
import { 排八字 } from './bazi'
import type { BirthInput } from './types'

const 四柱串 = (i: BirthInput) => {
  const b = 排八字(i.年, i.月, i.日, i.时, i.分, i.性别).四柱
  return `${b.年.天干}${b.年.地支} ${b.月.天干}${b.月.地支} ${b.日.天干}${b.日.地支} ${b.时.天干}${b.时.地支}`
}

describe('八字四柱', () => {
  it('基准命例 1996-08-12 14:30 男', () => {
    expect(四柱串({ 历法: '公历', 年: 1996, 月: 8, 日: 12, 时: 14, 分: 30, 性别: '男' }))
      .toBe('丙子 丙申 辛巳 乙未')
  })

  it('年柱按立春分界（非元旦）：立春前用上一年干支', () => {
    const 前 = 四柱串({ 历法: '公历', 年: 1990, 月: 2, 日: 3, 时: 12, 分: 0, 性别: '男' })
    const 后 = 四柱串({ 历法: '公历', 年: 1990, 月: 2, 日: 5, 时: 12, 分: 0, 性别: '男' })
    expect(前.split(' ')[0]).toBe('己巳') // 立春前仍属己巳年
    expect(后.split(' ')[0]).toBe('庚午') // 立春后转庚午年
  })

  it('子时命例 2000-01-01 23:00', () => {
    expect(四柱串({ 历法: '公历', 年: 2000, 月: 1, 日: 1, 时: 23, 分: 0, 性别: '男' }))
      .toBe('己卯 丙子 戊午 甲子')
  })
})

describe('紫微斗数', () => {
  it('基准命例命宫与五行局正确', () => {
    const z = 排盘({ 历法: '公历', 年: 1996, 月: 8, 日: 12, 时: 14, 分: 30, 性别: '男' }).紫微
    expect(z.五行局).toBe('土五局')
    expect(z.命宫地支).toBe('子')
    expect(z.十二宫).toHaveLength(12)
    const 命宫 = z.十二宫.find((g) => g.地支 === z.命宫地支)!
    expect(命宫.主星.map((s) => s.名)).toContain('天梁')
  })
})

describe('真太阳时校正', () => {
  it('上海经度时差约 +6 分，几乎不改时辰', () => {
    const c = 排盘({ 历法: '公历', 年: 1996, 月: 8, 日: 12, 时: 14, 分: 30, 性别: '男', 出生地: { 名称: '上海', 经度: 121.47 } })
    expect(c.元信息.真太阳时?.启用).toBe(true)
    expect(c.元信息.真太阳时?.经度时差分钟).toBe(6)
    expect(c.元信息.真太阳时?.跨日).toBe(false)
  })

  it('乌鲁木齐凌晨出生校正后跨日，改变日柱', () => {
    const 钟表 = 排盘({ 历法: '公历', 年: 2000, 月: 1, 日: 1, 时: 0, 分: 30, 性别: '男' })
    const 真太阳 = 排盘({ 历法: '公历', 年: 2000, 月: 1, 日: 1, 时: 0, 分: 30, 性别: '男', 出生地: { 名称: '乌鲁木齐', 经度: 87.62 } })
    expect(真太阳.元信息.真太阳时?.跨日).toBe(true)
    const 钟表日 = 钟表.八字.四柱.日.天干 + 钟表.八字.四柱.日.地支
    const 真太阳日 = 真太阳.八字.四柱.日.天干 + 真太阳.八字.四柱.日.地支
    expect(真太阳日).not.toBe(钟表日) // 校正退回前一天，日柱不同
  })

  it('不填出生地则不校正', () => {
    const c = 排盘({ 历法: '公历', 年: 1996, 月: 8, 日: 12, 时: 14, 分: 30, 性别: '男' })
    expect(c.元信息.真太阳时).toBeUndefined()
  })
  it('脏经度（NaN / 越界）不校正、不产出错盘', () => {
    const base = { 历法: '公历' as const, 年: 1996, 月: 8, 日: 12, 时: 14, 分: 30, 性别: '男' as const }
    for (const 经度 of [NaN, Infinity, 999, -300]) {
      const c = 排盘({ ...base, 出生地: { 名称: '脏数据', 经度 } })
      expect(c.元信息.真太阳时).toBeUndefined() // 跳过校正
      expect(c.元信息.公历计算?.时).toBe(14)     // 排盘时刻未被脏经度污染
    }
  })
})

describe('命盘结构', () => {
  it('农历输入可转公历并产出完整命盘', () => {
    const c = 排盘({ 历法: '农历', 年: 1996, 月: 6, 日: 28, 时: 14, 分: 30, 性别: '男' })
    expect(c.八字.四柱.日.天干).toBe('辛')
    expect(c.紫微.十二宫).toHaveLength(12)
  })
})

describe('支关系（每日一瞥个体化）', () => {
  it('六冲', () => { expect(支关系('子', '午')).toBe('冲'); expect(支关系('寅', '申')).toBe('冲') })
  it('六合', () => { expect(支关系('子', '丑')).toBe('合'); expect(支关系('午', '未')).toBe('合') })
  it('无关系返回 null', () => { expect(支关系('子', '寅')).toBeNull(); expect(支关系('辰', '巳')).toBeNull() })
})
