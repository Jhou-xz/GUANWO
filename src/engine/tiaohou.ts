export interface 调候 { 月令: string; 用神: string[]; 透: string[]; 藏: string[]; 标题: string }

// 算调候：用神来自表；透=用神出现在四天干，藏=用神藏于地支（未透）
export function 算调候(
  日干: string,
  月支: string,
  天干集: string[],
  藏干集: string[],
): 调候 | null {
  const mi = 月序.indexOf(月支)
  const row = 表[日干]
  if (mi < 0 || !row) return null
  const 用神 = Array.from(new Set(row[mi].split('')))
  const 透 = 用神.filter((u) => 天干集.includes(u))
  const 藏 = 用神.filter((u) => !天干集.includes(u) && 藏干集.includes(u))
  return { 月令: 月支, 用神, 透, 藏, 标题: `论${日干}生${月支}月` }
}
