    印 = 反查(我生, me)
    食伤 = 我生.get(me)
    财 = 我克.get(me)
    官杀 = 反查(我克, me)

    朝向 = '显' if 日主 in 阳干 else '隐'

    s_me = s.get(me, 0)
    s_印 = s.get(印, 0)
    s_食伤 = s.get(食伤, 0)
    s_财 = s.get(财, 0)
    s_官杀 = s.get(官杀, 0)

    扶 = s_me + s_印
    耗 = s_食伤 + s_财 + s_官杀
    月令 = bazi.get('五行旺衰', {}).get('月令五行') if bazi.get('五行旺衰') else None
    if 月令:
        if 月令 == me or 月令 == 印:
            扶 += 2
        else:
            耗 += 1
    底盘 = '主' if 扶 >= 耗 else '应'

    创力 = s_食伤 + s_财
    守力 = s_官杀 + s_印
    if 创力 > 守力:
        心法 = '创'
    elif 创力 < 守力:
        心法 = '守'
    else:
        心法 = '创' if 日主 in 阳干 else '守'

