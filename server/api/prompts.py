def 卦文(卦: dict, 标神: bool = True) -> str:
    lines = []
    for y in 卦.get('爻', []):
        阴阳 = '▅▅▅' if y.get('阳') else '▅ ▅'
        if y.get('变'):
            动 = '○动(老阳→阴)' if y.get('阳') else '×动(老阴→阳)'
        else:
            动 = ''
        
        神 = f"{y.get('六神')} " if (标神 and y.get('六神')) else ''
        
        marks = " ".join([m for m in [y.get('世应'), '空亡' if y.get('空亡') else '', 动] if m])
        marks_str = f"  {marks}" if marks else ''
        
        pos_name = 爻位名[y.get('位', 1) - 1]
        lines.append(
            f"  {pos_name}爻 {阴阳} {神}{y.get('干支', '')}{y.get('五行', '')} {y.get('六亲', '')}{marks_str}"
        )
    return "\n".join(lines)

