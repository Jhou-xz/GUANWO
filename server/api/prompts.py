        杂_str = f"｜杂{杂}" if 杂 else ''
        
        标 = ''
        if g.get('是身宫'):
            标 += '〔身宫〕'
        if g.get('是来因宫'):
            标 += '〔来因〕'
            
        shansha_list = [g.get('长生十二神'), g.get('博士十二神'), g.get('将前十二神'), g.get('岁前十二神')]
